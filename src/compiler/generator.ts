function authSource(): string {
  return `import {createRemoteJWKSet, jwtVerify} from 'jose';

export type AuthMode = 'none' | 'cloudflare-access' | 'external-jwt';
export type AuthUser = {
  id: string;
  email?: string;
  name?: string;
  provider?: 'google' | 'microsoft' | 'github';
  claims: Record<string, unknown>;
};

type AuthEnv = {
  CF_ACCESS_TEAM_DOMAIN?: string;
  CF_ACCESS_AUD?: string;
  JWT_ISSUER?: string;
  JWT_AUDIENCE?: string;
  JWT_JWKS_URL?: string;
};

export async function authenticate(request: Request, env: AuthEnv, mode: AuthMode): Promise<AuthUser | null> {
  if (mode === 'none') return null;
  const token = mode === 'cloudflare-access'
    ? request.headers.get('cf-access-jwt-assertion')
    : bearerToken(request.headers.get('authorization'));
  if (!token) return null;
  const issuer = mode === 'cloudflare-access'
    ? required(env.CF_ACCESS_TEAM_DOMAIN, 'CF_ACCESS_TEAM_DOMAIN').replace(new RegExp('/$'), '')
    : required(env.JWT_ISSUER, 'JWT_ISSUER');
  const audience = mode === 'cloudflare-access'
    ? required(env.CF_ACCESS_AUD, 'CF_ACCESS_AUD')
    : required(env.JWT_AUDIENCE, 'JWT_AUDIENCE');
  const jwksUrl = mode === 'cloudflare-access'
    ? new URL('/cdn-cgi/access/certs', issuer)
    : new URL(required(env.JWT_JWKS_URL, 'JWT_JWKS_URL'));
  try {
    const {payload} = await jwtVerify(token, createRemoteJWKSet(jwksUrl), {issuer, audience});
    if (typeof payload.sub !== 'string') return null;
    const user: AuthUser = {id: payload.sub, claims: payload};
    if (typeof payload.email === 'string') user.email = payload.email;
    if (typeof payload.name === 'string') user.name = payload.name;
    if (payload.provider === 'google' || payload.provider === 'microsoft' || payload.provider === 'github') {
      user.provider = payload.provider;
    }
    return user;
  } catch {
    return null;
  }
}

function bearerToken(value: string | null): string | null {
  const match = value?.match(/^Bearer\\s+(.+)$/i);
  return match?.[1] ?? null;
}

function required(value: string | undefined, name: string): string {
  if (!value) throw new Error(\`Missing secret or variable: \${name}\`);
  return value;
}
`;
}

function storageSource(): string {
  return `export type StoredRecord = {
  id: string;
  collection: string;
  ownerId: string | null;
  data: unknown;
  createdAt: string;
  updatedAt: string;
};

type RecordRow = {
  id: string;
  collection: string;
  owner_id: string | null;
  data_json: string;
  created_at: string;
  updated_at: string;
};

export interface RecordStore {
  create(collection: string, dataJson: string, ownerId?: string): Promise<StoredRecord>;
  list(collection: string): Promise<StoredRecord[]>;
  get(id: string): Promise<StoredRecord | null>;
  delete(id: string): Promise<boolean>;
}

export interface AssetStore { get(key: string): Promise<R2ObjectBody | null> }
export interface ConfigStore { get(key: string): Promise<string | null> }
export interface CounterStore { increment(key: string, amount: number): Promise<number> }

export async function createRecord(db: D1Database, collection: string, dataJson: string, ownerId?: string): Promise<StoredRecord> {
  const id = crypto.randomUUID();
  const now = new Date().toISOString();
  JSON.parse(dataJson);
  await db.prepare(
    'INSERT INTO records (id, collection, owner_id, data_json, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?)'
  ).bind(id, collection, ownerId ?? null, dataJson, now, now).run();
  return {id, collection, ownerId: ownerId ?? null, data: JSON.parse(dataJson), createdAt: now, updatedAt: now};
}

export async function listRecords(db: D1Database, collection: string): Promise<StoredRecord[]> {
  const result = await db.prepare(
    'SELECT id, collection, owner_id, data_json, created_at, updated_at FROM records WHERE collection = ? ORDER BY created_at DESC LIMIT 100'
  ).bind(collection).all<RecordRow>();
  return result.results.map(fromRow);
}

export async function getRecord(db: D1Database, id: string): Promise<StoredRecord | null> {
  const row = await db.prepare(
    'SELECT id, collection, owner_id, data_json, created_at, updated_at FROM records WHERE id = ?'
  ).bind(id).first<RecordRow>();
  return row ? fromRow(row) : null;
}

export async function deleteRecord(db: D1Database, id: string): Promise<boolean> {
  const result = await db.prepare('DELETE FROM records WHERE id = ?').bind(id).run();
  return result.meta.changes > 0;
}

function fromRow(row: RecordRow): StoredRecord {
  return {
    id: row.id,
    collection: row.collection,
    ownerId: row.owner_id,
    data: JSON.parse(row.data_json),
    createdAt: row.created_at,
    updatedAt: row.updated_at
  };
}
`;
}

