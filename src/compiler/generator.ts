function devVars(mode: AuthMode): string {
  if (mode === 'cloudflare-access') return 'CF_ACCESS_TEAM_DOMAIN=https://example.cloudflareaccess.com\nCF_ACCESS_AUD=replace-me\n';
  if (mode === 'external-jwt') return 'JWT_ISSUER=https://issuer.example/\nJWT_AUDIENCE=replace-me\nJWT_JWKS_URL=https://issuer.example/.well-known/jwks.json\n';
  return '# No secrets are required for auth mode none.\n';
}

function generatedReadme(ir: DeployIr): string {
  const routeTable = ir.routes.map((route) => `| ${route.method} | \`${route.path}\` | ${route.auth} |`).join('\n');
  return `# ${ir.name}

Generated Cloudflare Workers + Hono application.

| Method | Path | Auth |
|---|---|---|
${routeTable}

## Setup

1. Run \`pnpm install\`.
2. Create a D1 database and replace \`REPLACE_WITH_D1_DATABASE_ID\` in \`wrangler.jsonc\`.
3. Run \`pnpm wrangler d1 migrations apply DB --local\` for local development.
4. Copy \`.dev.vars.example\` to \`.dev.vars\` and fill required auth values.
5. Run \`pnpm dev\`, then deploy explicitly with \`pnpm deploy\`.

Secrets must be configured with \`wrangler secret put\` or the Cloudflare dashboard; never commit \`.dev.vars\`.

## Storage adapters

- D1: record store (enabled by default).
- R2: binary assets; add the commented \`ASSETS\` binding when used.
- KV: read-heavy configuration/cache only; add the commented \`CONFIG\` binding when used.
- Durable Objects: intentionally not generated. Use only for exact counters or coordinated realtime state.

## Rollback

The generator does not modify the TurboWarp bridge. Stop deploying this generated project to return to the bridge workflow. To remove Cloudflare resources, first export data if needed, then use \`wrangler delete\`, \`wrangler d1 delete <database>\`, and the corresponding R2/KV delete commands for resources you created.
`;
}

function packageName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '') || 'turbowarp-worker';
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function indent(value: string, spaces: number): string {
  const prefix = ' '.repeat(spaces);
  return value.split('\n').map((line) => (line.length > 0 ? prefix + line : line)).join('\n');
}
